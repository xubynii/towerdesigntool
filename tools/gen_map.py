# Builds map/vancouver.js for the Tower Workspace's "Select site boundary" screen from the Vancouver Tall competition
# base model (sun-wind-studio/site.json: metres, +y north, origin at the parcel centre). Run:
#   python -I tools/gen_map.py [path/to/site.json]
# Out: window.TW_MAPS.vancouver = { name, lat, lon, extent, site, blocks, curbs, buildings, outlines, future, labels, uses }
import json, io, os, sys
SRC = sys.argv[1] if len(sys.argv) > 1 else r"C:/Users/sinnie/OneDrive/Desktop/sun-wind-studio/site.json"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'map', 'vancouver.js')
d = json.load(io.open(SRC, encoding='utf-8'))
r1 = lambda v: round(v, 1)
ring = lambda pts: [[r1(p[0]), r1(p[1])] for p in pts]

def clean(pts):
    out = []
    for p in ring(pts):
        if not out or out[-1] != p: out.append(p)
    if len(out) > 1 and out[0] == out[-1]: out.pop()
    return out

curves = {}
for c in d['curves']:
    if c.get('closed') and len(c['pts']) >= 3: curves.setdefault(c['layer'], []).append(clean(c['pts']))

# buildings: footprints of the meshes that stand on the ground, as boxes with their height (as tools/gen_site.py of the Flow Lab does)
def boxes(layer):
    out = []
    for m in d['meshes']:
        if m['layer'] != layer: continue
        v = m['v']; P = [(v[i], v[i + 1], v[i + 2]) for i in range(0, len(v), 3)]
        z0 = min(p[2] for p in P)
        if z0 > 0.5: continue
        fp = [p for p in P if abs(p[2] - z0) < 0.05]
        xs = [p[0] for p in fp]; ys = [p[1] for p in fp]
        b = [min(xs), min(ys), max(xs), max(ys), m['top']]
        if (b[2] - b[0]) * (b[3] - b[1]) < 30 or b[2] - b[0] < 3 or b[3] - b[1] < 3: continue
        out.append(b)
    return out
def inside(b, c, frac=0.8):
    ix = max(0, min(b[2], c[2]) - max(b[0], c[0])); iy = max(0, min(b[3], c[3]) - max(b[1], c[1]))
    return ix * iy >= frac * (b[2] - b[0]) * (b[3] - b[1])
blds = []
for layer in ('existing', 'heritage'):
    raw = sorted(boxes(layer), key=lambda b: -(b[2] - b[0]) * (b[3] - b[1])); kept = []
    for b in raw:
        if any(inside(b, k) and k[4] >= b[4] - 0.5 for k in kept): continue
        kept.append(b)
    blds += [{'x0': r1(b[0]), 'y0': r1(b[1]), 'x1': r1(b[2]), 'y1': r1(b[3]), 'h': r1(b[4]), 'layer': layer} for b in kept]

xs = [p[0] for L in curves.values() for r in L for p in r]; ys = [p[1] for L in curves.values() for r in L for p in r]
seen = set(); labels = []
for l in d['labels']:
    t = ' '.join(l['text'].replace('\r', ' ').split()); key = (t, round(l['pos'][0] / 5), round(l['pos'][1] / 5))
    if key in seen: continue
    seen.add(key); labels.append({'t': t, 'x': r1(l['pos'][0]), 'y': r1(l['pos'][1])})
out = {
    'name': 'Vancouver Tall competition base model', 'city': 'Vancouver', 'lat': d['meta']['lat'], 'lon': d['meta']['lon'],
    'extent': [r1(min(xs)), r1(min(ys)), r1(max(xs)), r1(max(ys))],
    'site': ring(d['site']['polygon']), 'siteArea': d['site']['area'],
    'blocks': curves.get('block', []), 'curbs': curves.get('curb', []), 'outlines': curves.get('outline', []) + curves.get('tower', []),
    'buildings': blds, 'future': [{'pts': ring(f['pts']), 'base': r1(f['base']), 'top': r1(f['top'])} for f in d['future']],
    'labels': labels, 'uses': [{'cat': u['cat'], 'x': r1(u['x'] + u['w'] / 2), 'y': r1(u['y'] + u['h'] / 2)} for u in d['uses']],
}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with io.open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/gen_map.py from the Vancouver Tall competition base model (sun-wind-studio/site.json). Metres, +y north, origin at the parcel centre.\n')
    f.write('window.TW_MAPS = window.TW_MAPS || {};\nwindow.TW_MAPS.vancouver = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes;', len(out['blocks']), 'blocks,', len(out['curbs']), 'curbs,', len(out['buildings']), 'buildings,', len(out['outlines']), 'outlines,', len(labels), 'labels, extent', out['extent'])
